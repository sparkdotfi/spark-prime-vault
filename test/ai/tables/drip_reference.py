#!/usr/bin/env python3
"""Reference generator for test/Rounding.t.sol (standard library only).

Mirrors SparkPrimeVault._rpow (half-up at every squaring / multiply step) with exact integer
arithmetic and writes:

  test/tables/drip.csv        rows: vsr,seconds,chi0,expected_chi
  test/tables/DripTable.sol   the same rows as a Solidity library (foundry.toml grants no
                              fs_permissions, so the test cannot vm.readFile the CSV)

and prints, for the report: the harness start indexes, the drift of _rpow compounding against
the continuous formula chi0 * exp(t * ln(vsr)), and a brute-force maximum round-trip loss at the
harness indexes.

Run from the repo root:  python3 -I test/tables/drip_reference.py
"""

import os
import sys
from decimal import Decimal, getcontext

RAY = 10**27
MAX_U256 = 2**256

VSR = {
    "ONE_PCT_VSR":    1_000000000315522921573372069,
    "FOUR_PCT_VSR":   1_000000001243680656318820312,
    "FIVE_PCT_VSR":   1_000000001547125957863212448,
    "TEN_PCT_VSR":    1_000000003022265980097387650,
    "FORTY_PCT_VSR":  1_000000010669464688489416886,
    "MAX_VSR":        1_000000021979553151239153027,
    "UGLY_SP_VSR":    1_000000001356138789912371417,
    "UGLY_PRIME_VSR": 1_000000000906634632573938893,
}

DAY = 86400
DURATIONS = [
    ("1s",   1),
    ("60s",  60),
    ("1h",   3600),
    ("1d",   DAY),
    ("30d",  30 * DAY),
    ("365d", 365 * DAY),
    ("10y",  10 * 365 * DAY),
]

# LocalTestBase.setUp: spUSDC runs UGLY_SP_VSR for 397d + 12345s, spPRIME runs UGLY_PRIME_VSR
# for 123d + 6789s, both from chi = RAY.
HARNESS_SP_SECS    = 397 * DAY + 12345
HARNESS_PRIME_SECS = 123 * DAY + 6789


def rpow(x, n):
    """Exact mirror of the assembly _rpow, including its overflow reverts."""
    if x == 0:
        return RAY if n == 0 else 0
    z = RAY if n % 2 == 0 else x
    half = RAY // 2
    n //= 2
    while n:
        xx = x * x
        if xx >= MAX_U256:
            raise OverflowError("rpow: x*x overflow")
        xx_round = xx + half
        if xx_round >= MAX_U256:
            raise OverflowError("rpow: xxRound overflow")
        x = xx_round // RAY
        if n % 2:
            zx = z * x
            if zx >= MAX_U256:
                raise OverflowError("rpow: z*x overflow")
            zx_round = zx + half
            if zx_round >= MAX_U256:
                raise OverflowError("rpow: zxRound overflow")
            z = zx_round // RAY
        n //= 2
    return z


def now_chi(vsr, secs, chi0):
    """SparkPrimeVault.nowChi / drip for a single step."""
    if secs == 0:
        return chi0
    return rpow(vsr, secs) * chi0 // RAY


def continuous_chi(vsr, secs, chi0):
    """chi0 * vsr^secs with 80 significant digits (Decimal), as a Decimal in RAY units."""
    getcontext().prec = 80
    return Decimal(chi0) * (Decimal(vsr) / Decimal(RAY)) ** secs


def divup(x, y):
    return 0 if x == 0 else (x - 1) // y + 1


def round_trip_loss(x, chi_s, chi_p):
    """USDC lost on deposit X -> instant fill -> redeem all (fee 0), same chis throughout."""
    s = x * RAY // chi_s                 # R1  spUSDC.deposit            floor
    a = s * chi_s // RAY                 # R3  spUSDC.convertToAssets    floor
    m = a * RAY // chi_p                 # R4  convertToShares           floor
    out = m * chi_p // RAY               # R8  convertToAssets           floor
    return x - out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    csv_path = os.path.join(here, "drip.csv")
    sol_path = os.path.join(here, "DripTable.sol")

    chi_s0 = now_chi(VSR["UGLY_SP_VSR"], HARNESS_SP_SECS, RAY)
    chi_p0 = now_chi(VSR["UGLY_PRIME_VSR"], HARNESS_PRIME_SECS, RAY)

    print(f"harness chi_s (spUSDC)  = {chi_s0}")
    print(f"harness chi_p (spPRIME) = {chi_p0}")

    rows = []
    for chi0 in (RAY, chi_p0):
        for name, vsr in VSR.items():
            for dname, secs in DURATIONS:
                rows.append((name, dname, vsr, secs, chi0, now_chi(vsr, secs, chi0)))

    with open(csv_path, "w") as f:
        f.write("vsr,seconds,chi0,expected_chi\n")
        for _, _, vsr, secs, chi0, chi in rows:
            f.write(f"{vsr},{secs},{chi0},{chi}\n")

    with open(sol_path, "w") as f:
        f.write("// SPDX-License-Identifier: AGPL-3.0-or-later\n")
        f.write("pragma solidity ^0.8.34;\n\n")
        f.write("// GENERATED by test/tables/drip_reference.py. Do not edit by hand.\n")
        f.write("// Reference values for SparkPrimeVault.nowChi()/drip(): chi = _rpow(vsr, seconds) * chi0 / RAY\n")
        f.write("// with _rpow mirrored exactly (half-up at each squaring and multiply step).\n")
        f.write("library DripTable {\n\n")
        f.write("    struct Row {\n")
        f.write("        uint256 vsr;\n")
        f.write("        uint256 seconds_;\n")
        f.write("        uint256 chi0;\n")
        f.write("        uint256 expectedChi;\n")
        f.write("    }\n\n")
        f.write(f"    uint256 internal constant HARNESS_CHI_S = {chi_s0};\n")
        f.write(f"    uint256 internal constant HARNESS_CHI_P = {chi_p0};\n\n")
        f.write(f"    function rows() internal pure returns (Row[] memory rows_) {{\n")
        f.write(f"        rows_ = new Row[]({len(rows)});\n")
        for i, (name, dname, vsr, secs, chi0, chi) in enumerate(rows):
            chi0_s = "RAY" if chi0 == RAY else "ugly"
            f.write(f"        rows_[{i:3d}] = Row({vsr}, {secs}, {chi0}, {chi});"
                    f"  // {name} {dname} chi0={chi0_s}\n")
        f.write("    }\n\n}\n")

    print(f"wrote {len(rows)} rows to {os.path.relpath(csv_path)} and {os.path.relpath(sol_path)}")

    # Drift of _rpow against the continuous (exact real) compounding, RAY units, chi0 = RAY.
    print("\n_rpow vs continuous chi0*vsr^t (RAY units, positive = _rpow above exact):")
    print(f"{'vsr':16s} {'t':6s} {'rpow':>30s} {'exact (rounded)':>30s} {'drift':>8s}")
    for name in ("FOUR_PCT_VSR", "FIVE_PCT_VSR", "MAX_VSR"):
        vsr = VSR[name]
        for dname, secs in (("365d", 365 * DAY), ("10y", 10 * 365 * DAY)):
            r = now_chi(vsr, secs, RAY)
            e = continuous_chi(vsr, secs, RAY)
            e_int = int(e.to_integral_value(rounding="ROUND_HALF_UP"))
            print(f"{name:16s} {dname:6s} {r:30d} {e_int:30d} {r - e_int:8d}")

    # Brute-force maximum round-trip loss at the harness indexes.
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else 2_000_000
    worst = (0, 0)
    hist = {}
    for x in range(1, limit + 1):
        loss = round_trip_loss(x, chi_s0, chi_p0)
        hist[loss] = hist.get(loss, 0) + 1
        if loss > worst[0]:
            worst = (loss, x)
    bound = 2 + Decimal(chi_s0) / RAY + Decimal(chi_p0) / RAY
    print(f"\nround-trip loss, X in [1, {limit}] at harness chis: max {worst[0]} wei (first at X={worst[1]}),"
          f" histogram {dict(sorted(hist.items()))}, proven bound loss < {bound} wei")


if __name__ == "__main__":
    main()
